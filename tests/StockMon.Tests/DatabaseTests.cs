using Npgsql;
using StockMon.Infrastructure;

namespace StockMon.Tests;

public sealed class DatabaseFactAttribute : FactAttribute
{
    public DatabaseFactAttribute()
    {
        if (string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("STOCKMON_TEST_ADMIN_DSN")))
            Skip = "PostgreSQL integration environment unavailable; run scripts/test-db.ps1. This is not a pass.";
    }
}

public sealed class DatabaseTests
{
    [DatabaseFact]
    [Trait("Category", "Database")]
    public async Task MigrationRolesRlsRevocationPoolingAndAuditAreEnforced()
    {
        var dsn = Environment.GetEnvironmentVariable("STOCKMON_TEST_ADMIN_DSN")!;
        await using var admin = NpgsqlDataSource.Create(dsn);
        await DatabaseMigrator.ApplyAsync(admin);
        await DatabaseMigrator.ApplyAsync(admin);
        Assert.Equal(1L, await Scalar(admin, "SELECT count(*) FROM public.stockmon_migrations"));
        var password = Convert.ToHexString(System.Security.Cryptography.RandomNumberGenerator.GetBytes(24));
        // Random hex is generated by the test, not supplied by a request or configuration file.
        foreach (var role in new[] { "sm_test_self", "sm_test_other", "sm_test_viewer", "sm_test_operator", "sm_test_collector", "sm_test_unmapped" })
            await Execute(admin, $"CREATE ROLE {role} LOGIN PASSWORD '{password}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS; GRANT stockmon_reader TO {role}");
        await Execute(admin, "GRANT stockmon_collector TO sm_test_collector");
        await Execute(admin, """
            INSERT INTO stockmon.owners VALUES ('OWNER-SELF'), ('OWNER-A');
            INSERT INTO stockmon.accounts(id,owner_id,broker,product,environment) VALUES
                ('ACC-02','OWNER-SELF','Kis','Domestic','Live'), ('ACC-05','OWNER-A','Kis','Domestic','Live');
            INSERT INTO stockmon.principals(id,db_login,role,owner_id,active) VALUES
                ('P-SELF','sm_test_self','owner','OWNER-SELF',true),
                ('P-A','sm_test_other','owner','OWNER-A',true),
                ('P-VIEWER','sm_test_viewer','account_viewer','OWNER-SELF',true),
                ('P-OPERATOR','sm_test_operator','operator','OWNER-SELF',true),
                ('P-COLLECTOR','sm_test_collector','collector','OWNER-SELF',true);
            """);
        await using var self = User("sm_test_self");
        await using var other = User("sm_test_other");
        await using var viewer = User("sm_test_viewer");
        await using var op = User("sm_test_operator");
        await using var collector = User("sm_test_collector");
        await using var unmapped = User("sm_test_unmapped");
        Assert.Equal(new[] { "ACC-02" }, await new AccountReader(self).ListIdsAsync());
        Assert.Equal(new[] { "ACC-05" }, await new AccountReader(other).ListIdsAsync());
        Assert.Empty(await new AccountReader(viewer).ListIdsAsync());
        Assert.Empty(await new AccountReader(op).ListIdsAsync());
        Assert.Empty(await new AccountReader(unmapped).ListIdsAsync());
        Assert.Equal(0L, await Scalar(self, "SELECT count(*) FROM stockmon.accounts WHERE owner_id='OWNER-A'"));
        await Execute(self, "SET app.owner_id='OWNER-A'; SET app.principal_id='P-A'");
        // MaxPoolSize=1 deliberately reuses the physical connection after spoofed settings.
        Assert.Equal(new[] { "ACC-02" }, await new AccountReader(self).ListIdsAsync());
        Assert.Equal(0L, await Scalar(admin, "SELECT count(*) FROM pg_roles WHERE rolname LIKE 'sm_test_%' AND (rolsuper OR rolbypassrls OR rolcreaterole)"));
        Assert.Equal(0L, await Scalar(admin, "SELECT count(*) FROM pg_tables WHERE schemaname='stockmon' AND tableowner LIKE 'sm_test_%'"));
        await Denied(self, "SELECT * FROM stockmon.access_grants");
        await Denied(self, "UPDATE stockmon.accounts SET owner_id='OWNER-SELF' WHERE id='ACC-05'");
        await Denied(self, "SET ROLE sm_test_other");
        await Denied(self, "SELECT * FROM stockmon.audit_events");

        await Execute(admin, """
            INSERT INTO stockmon.access_grants(principal_id,account_id,owner_id,permission,expires_at,evidence_ref) VALUES
                ('P-VIEWER','ACC-05','OWNER-A','detail',now()+interval '1 day','synthetic-proof'),
                ('P-OPERATOR','ACC-05','OWNER-A','detail',now()+interval '1 day','synthetic-proof'),
                ('P-COLLECTOR','ACC-02','OWNER-SELF','collect',now()+interval '1 day','synthetic-proof'),
                ('P-COLLECTOR','ACC-05','OWNER-A','collect',now()+interval '1 day','synthetic-proof');
            """);
        Assert.Empty(await new AccountReader(viewer).ListIdsAsync());
        await Execute(admin, """
            INSERT INTO stockmon.consents(owner_id,principal_id,permission,expires_at,evidence_ref) VALUES
                ('OWNER-A','P-VIEWER','detail',now()+interval '1 day','synthetic-consent'),
                ('OWNER-A','P-OPERATOR','detail',now()+interval '1 day','synthetic-consent'),
                ('OWNER-A','P-COLLECTOR','collect',now()+interval '1 day','synthetic-consent');
            """);
        Assert.Equal(new[] { "ACC-05" }, await new AccountReader(viewer).ListIdsAsync());
        Assert.Empty(await new AccountReader(op).ListIdsAsync());
        Assert.Equal(false, await Scalar(viewer, "SELECT stockmon.can_access('ACC-05','OWNER-A','aggregate')"));
        Assert.Equal(new[] { "ACC-02" }, await new AccountReader(collector).ListIdsAsync());
        await Execute(collector, "INSERT INTO stockmon.account_observations(account_id,owner_id,as_of,quality) VALUES ('ACC-02','OWNER-SELF',now(),'Synthetic')");
        await Denied(collector, "INSERT INTO stockmon.account_observations(account_id,owner_id,as_of,quality) VALUES ('ACC-05','OWNER-A',now(),'Synthetic')");
        var mismatch = await Assert.ThrowsAsync<PostgresException>(() => Execute(admin,
            "INSERT INTO stockmon.account_observations(account_id,owner_id,as_of,quality) VALUES ('ACC-02','OWNER-A',now(),'Synthetic')"));
        Assert.Equal(PostgresErrorCodes.ForeignKeyViolation, mismatch.SqlState);
        var duplicate = await Assert.ThrowsAsync<PostgresException>(() => Execute(admin,
            "INSERT INTO stockmon.accounts(id,owner_id,broker,product,environment) VALUES ('ACC-02','OWNER-SELF','Kis','Domestic','Live')"));
        Assert.Equal(PostgresErrorCodes.UniqueViolation, duplicate.SqlState);

        await Execute(admin, "UPDATE stockmon.access_grants SET expires_at=now()-interval '1 second' WHERE principal_id='P-VIEWER'");
        Assert.Empty(await new AccountReader(viewer).ListIdsAsync());
        await Execute(admin, "UPDATE stockmon.access_grants SET expires_at=now()+interval '1 day' WHERE principal_id='P-VIEWER'");
        Assert.Single(await new AccountReader(viewer).ListIdsAsync());
        await Execute(admin, "UPDATE stockmon.consents SET revoked_at=now() WHERE principal_id='P-VIEWER'");
        Assert.Empty(await new AccountReader(viewer).ListIdsAsync());
        await Execute(admin, "UPDATE stockmon.principals SET active=false WHERE id='P-SELF'");
        Assert.Empty(await new AccountReader(self).ListIdsAsync());
        Assert.True((long)(await Scalar(admin, "SELECT count(*) FROM stockmon.audit_events WHERE entity='consents' AND operation='UPDATE'"))! > 0);
        await Denied(collector, "DELETE FROM stockmon.audit_events");
        await Execute(admin, "UPDATE public.stockmon_migrations SET sha256='changed' WHERE version=1");
        await Assert.ThrowsAsync<InvalidOperationException>(() => DatabaseMigrator.ApplyAsync(admin));

        NpgsqlDataSource User(string name)
        {
            var options = new NpgsqlConnectionStringBuilder(dsn) { Username = name, Password = password, MaxPoolSize = 1 };
            return NpgsqlDataSource.Create(options.ConnectionString);
        }
    }

    private static async Task Execute(NpgsqlDataSource db, string sql)
    {
        await using var command = db.CreateCommand(sql);
        await command.ExecuteNonQueryAsync();
    }
    private static async Task<object?> Scalar(NpgsqlDataSource db, string sql)
    {
        await using var command = db.CreateCommand(sql);
        return await command.ExecuteScalarAsync();
    }
    private static async Task Denied(NpgsqlDataSource db, string sql)
    {
        var error = await Assert.ThrowsAsync<PostgresException>(() => Execute(db, sql));
        Assert.Equal(PostgresErrorCodes.InsufficientPrivilege, error.SqlState);
    }
}
